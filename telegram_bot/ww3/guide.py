def send_guide_menu(chat_id, message_id=None):
    """نمایش منوی راهنما — با editMessageText"""
    rows = []
    row = []
    for key, title, _ in GUIDE_SECTIONS:
        row.append({"text": title, "callback_data": f"guide_{key}"})
        if len(row) == 2:
            rows.append(row)
            row = []
    if row:
        rows.append(row)
    rows.append([{"text": "🔙 داشبورد", "callback_data": "dashboard"}])
    
    text = (
        "📖 **راهنمای بازی جنگ جهانی**\n━━━━━━━━━━━━━━━━━━\n"
        "سلام فرمانده! 👋\n"
        "اینجا همه چیزهایی که برای شروع لازم داری قدم به قدم توضیح داده شده.\n\n"
        "💡 تاکتیک‌های برد عمداً اینجا نیست — آن‌ها را باید خودت با تجربه کشف کنی!\n"
        "یک بخش را انتخاب کن:"
    )
    keyboard = {"inline_keyboard": rows}
    
    # 🔄 اگر message_id داشتیم، ویرایش کن؛ وگرنه پیام جدید
    if message_id:
        result = edit_message(chat_id, message_id, text, keyboard)
        if result:
            return
    send_message(chat_id, text, keyboard)


def handle_guide(chat_id, user_id, data, message_id=None):
    """پردازش callbackهای راهنما — با editMessageText"""
    if data == "guide":
        send_guide_menu(chat_id, message_id=message_id)
        return
    
    key = data.replace("guide_", "")
    idx = None
    for i, (k, _, _) in enumerate(GUIDE_SECTIONS):
        if k == key:
            idx = i
            break
    if idx is None:
        send_guide_menu(chat_id, message_id=message_id)
        return
    
    _, title, text = GUIDE_SECTIONS[idx]
    
    # دکمه‌های ناوبری
    nav = []
    if idx > 0:
        nav.append({"text": "◀️ قبلی", "callback_data": "guide_" + GUIDE_SECTIONS[idx - 1][0]})
    nav.append({"text": "📖 فهرست", "callback_data": "guide"})
    if idx + 1 < len(GUIDE_SECTIONS):
        nav.append({"text": "بعدی ▶️", "callback_data": "guide_" + GUIDE_SECTIONS[idx + 1][0]})
    
    rows = [nav, [{"text": "🔙 داشبورد", "callback_data": "dashboard"}]]
    full_text = f"{title}\n━━━━━━━━━━━━━━━━━━\n\n{text}"
    keyboard = {"inline_keyboard": rows}
    
    # 🔄 اگر message_id داشتیم، ویرایش کن؛ وگرنه پیام جدید
    if message_id:
        result = edit_message(chat_id, message_id, full_text, keyboard)
        if result:
            return
    send_message(chat_id, full_text, keyboard)